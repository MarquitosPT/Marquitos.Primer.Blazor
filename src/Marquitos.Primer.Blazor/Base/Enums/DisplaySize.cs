namespace Marquitos.Primer.Blazor.Base.Enums
{
    /// <summary>
    /// Represents the different display sizes for responsive design.
    /// </summary>
    public enum DisplaySize
    {
        /// <summary>
        /// Represents a screen size smaller than 576px
        /// </summary>
        XSmall,
        /// <summary>
        /// Represents a screen size between 576px and 768px
        /// </summary>
        Small,
        /// <summary>
        /// Represents a screen size between 768px and 992px
        /// </summary>
        Medium,
        /// <summary>
        /// Represents a screen size between 992px and 1200px
        /// </summary>
        Large,
        /// <summary>
        /// Represents a screen size between 1200px and 1400px
        /// </summary>
        XLarge,
        /// <summary>
        /// Represents a screen size larger than 1400px
        /// </summary>
        XXLarge
    }
}
